ll modex(ll a, ll b, ll mod){
    if(b==0) return 1;
    ll t = modex(a,b/2, mod);
    if(b%2==0) return (t*t)%mod;
    else return (((t*t)%mod)*a)%mod;
}

void sol(){
    ll a,b,c;
    cin >> a >> b >> c;
    ll power = modex(b,c, MOD-1);
    o1(modex(a,power,MOD));
}

