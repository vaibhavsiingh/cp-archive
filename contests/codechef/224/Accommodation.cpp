void sol(){
    ll b,g,x,y,n;
    i2(b,g);
    i2(x,y);
    cin >> n;

    if(x+y>n){
        o1(-1);
        return;
    }

    if((b)/x<(g)/y){
        swap(b,g);
        swap(x,y);
    }

    ll cnt = g/y;
    ll boys_used  = min(cnt*x, b);
    ll space_rem = cnt*n - b - g;
    if(space_rem< 0){
        o1(-1);
    }
    else o1(cnt - (space_rem/n));
}

