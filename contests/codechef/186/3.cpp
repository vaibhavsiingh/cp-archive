const ll MOD = 998244353;

void sol(){
    ll n;
    cin >> n;
    vll a(n);
    iArray(a,n);
    sort(a.begin(),a.end());
    ll ans = a[0];
    for(int i=1;i<n; i++){
        ll choices= a[i]-(i);
        if(choices<=0){
            o1(0);
            return;
        }
        ans = (ans*choices)%MOD;
    }
    o1(ans);
}

