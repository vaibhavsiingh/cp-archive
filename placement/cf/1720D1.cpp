void sol(){
    ll n;
    cin >> n;

    vll a(n);
    iArray(a,n);

    vll dp(n);
    dp[0] = 1;

    for(int i=1; i<n; i++){
        ll mx = 1;
        for(ll j=i-1; j>=i-400 && j>=0; j--){
            if((a[j] ^ i) < (a[i] ^ j)){
              //  o1("here");
                mx = max(mx, dp[j]+1);
            }
        }
        dp[i] = mx;
    }
    o1(*max_element(all(dp)));
}

